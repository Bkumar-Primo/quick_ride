export function getInterpolatedGpsPoint(
  points: [number, number][],
  t: number,
): {
  lon: number;
  lat: number;
  angle: number;
  remainingGpsPoints: [number, number][];
} {
  if (points.length === 0) {
    return { lon: 76.685615, lat: 30.706081, angle: 0, remainingGpsPoints: [] };
  }
  if (points.length === 1 || t <= 0) {
    return { lon: points[0][0], lat: points[0][1], angle: 0, remainingGpsPoints: points };
  }
  if (t >= 1) {
    const last = points[points.length - 1];
    return { lon: last[0], lat: last[1], angle: 0, remainingGpsPoints: [last] };
  }

  const segmentLengths: number[] = [];
  let totalLength = 0;
  for (let i = 0; i < points.length - 1; i++) {
    const dLon = points[i + 1][0] - points[i][0];
    const dLat = points[i + 1][1] - points[i][1];
    const dist = Math.hypot(dLon, dLat);
    segmentLengths.push(dist);
    totalLength += dist;
  }

  const targetDist = t * totalLength;
  let accumulated = 0;

  for (let i = 0; i < segmentLengths.length; i++) {
    const len = segmentLengths[i];
    if (accumulated + len >= targetDist || i === segmentLengths.length - 1) {
      const segT = len > 0 ? (targetDist - accumulated) / len : 1;
      const p1 = points[i];
      const p2 = points[i + 1];
      const currentLon = p1[0] + segT * (p2[0] - p1[0]);
      const currentLat = p1[1] + segT * (p2[1] - p1[1]);

      // Heading angle along road segment
      const dLon = p2[0] - p1[0];
      const dLat = p2[1] - p1[1];
      const angle = (Math.atan2(-dLat, dLon) * 180) / Math.PI;

      const remainingGpsPoints: [number, number][] = [
        [currentLon, currentLat],
        ...points.slice(i + 1),
      ];

      return {
        lon: currentLon,
        lat: currentLat,
        angle,
        remainingGpsPoints,
      };
    }
    accumulated += len;
  }

  const last = points[points.length - 1];
  return { lon: last[0], lat: last[1], angle: 0, remainingGpsPoints: [last] };
}
